"""
schema.py - Data Models for the AI Study Planner.

This module defines the data structures using Pydantic.
Pydantic ensures that all user inputs and agent outputs are
strictly validated with proper data types (strings, dates, numbers, lists).
"""

import datetime as dt
from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field


class DifficultyLevel(str, Enum):
    """Enumeration of possible difficulty levels for a topic."""
    EASY = "easy"
    MEDIUM = "medium"
    HARD = "hard"


class Topic(BaseModel):
    """Represents an individual study topic within a subject."""
    name: str = Field(..., description="Name or title of the topic")
    difficulty: DifficultyLevel = Field(
        default=DifficultyLevel.MEDIUM,
        description="Difficulty of the topic: easy, medium, or hard"
    )


class Subject(BaseModel):
    """Represents an academic subject with its exam date and syllabus topics."""
    name: str = Field(..., description="Name of the subject (e.g. Mathematics)")
    exam_date: dt.date = Field(..., description="Date of the final exam for this subject")
    topics: List[Topic] = Field(default_factory=list, description="List of topics under this subject")


class StudyPlanRequest(BaseModel):
    """All user inputs collected from the Streamlit UI to create a study plan."""
    subjects: List[Subject] = Field(..., min_length=1, description="List of subjects to study")
    start_date: dt.date = Field(..., description="Date when the student starts studying")
    daily_max_hours: float = Field(
        ...,
        gt=0,
        le=24,
        description="Maximum study hours the student can commit each day (0 to 24)"
    )


class StudySession(BaseModel):
    """A single study session dedicated to a specific topic on a specific day."""
    subject: str = Field(..., description="Subject name")
    topic: str = Field(..., description="Topic name")
    hours: float = Field(..., gt=0, le=24, description="Hours allocated for this topic")


class DayPlan(BaseModel):
    """Daily schedule containing study sessions allocated for a specific date."""
    date: dt.date = Field(..., description="Date for these study sessions")
    sessions: List[StudySession] = Field(
        default_factory=list,
        description="List of study sessions scheduled on this day"
    )

    @property
    def total_hours(self) -> float:
        """Helper to quickly calculate total study hours scheduled for this day."""
        return sum(session.hours for session in self.sessions)


class StudySchedule(BaseModel):
    """Complete day-by-day study timetable generated by the AI agent."""
    days: List[DayPlan] = Field(
        default_factory=list,
        description="Day-by-day breakdown of the study schedule"
    )
    summary: Optional[str] = Field(
        default="",
        description="A brief friendly summary or strategy note from the AI agent"
    )


class ValidationResult(BaseModel):
    """Result of checking a generated schedule against study rules."""
    is_valid: bool = Field(..., description="True if the schedule passes all validation rules")
    errors: List[str] = Field(
        default_factory=list,
        description="List of critical rule violations that must be fixed"
    )
    warnings: List[str] = Field(
        default_factory=list,
        description="List of minor suggestions or non-breaking observations"
    )
